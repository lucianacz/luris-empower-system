const defaultFinanceTimeZone = "America/Costa_Rica";

export function currentFinanceDate(date = new Date(), timeZone = process.env.FINANCE_TIME_ZONE || defaultFinanceTimeZone) {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(date);
  const value = Object.fromEntries(parts.map((part) => [part.type, part.value]));
  return `${value.year}-${value.month}-${value.day}`;
}
